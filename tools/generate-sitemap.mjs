/**
 * Regenerate sitemap.xml from the live Supabase package list.
 *
 * Static pages are listed below; package detail URLs are pulled from the
 * `packages` table so the sitemap never goes stale when you add a package
 * in the dashboard.
 *
 *   node tools/generate-sitemap.mjs
 *
 * Requires Node 18+ (uses the built-in fetch). No dependencies.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SITE = 'https://luxpathtravel.com';

